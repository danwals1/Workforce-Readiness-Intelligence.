-- ============================================================================
-- IntegrateU Workforce Readiness Intelligence
-- 0007_assessment_direct_master_delivery.sql
--
-- PURPOSE
-- Allows employees to take IntegrateU master/template assessments directly
-- without first requiring the company to adopt/copy the role, competencies,
-- and assessment.
--
-- ADDS
--   1. Master-competency scoring support
--   2. Direct master-assessment attempt creation
--   3. 1–4 database-level proficiency enforcement
--   4. Self-service RLS for employees taking their own assessments
--   5. Materialized Technician I assessment questions
--   6. Updated scoring for both template-mode and company-mode assessments
--
-- PRESERVES
--   - Existing company assessment mode
--   - Existing assessment attempts
--   - Existing answer-key security
--   - Existing role/competency structures
-- ============================================================================


-- ============================================================================
-- PART 1 — COMPETENCY SCORES CAN REFERENCE MASTER OR COMPANY COMPETENCIES
-- ============================================================================

alter table competency_scores
add column if not exists master_competency_template_id uuid
references master_competency_templates(id);


alter table competency_scores
alter column competency_id drop not null;


create index if not exists ix_scores_master_competency
on competency_scores(master_competency_template_id);


-- Existing company scores continue using competency_id.
-- New master-assessment scores use master_competency_template_id.
--
-- Exactly one source must be populated.

alter table competency_scores
drop constraint if exists competency_scores_competency_source_check;


alter table competency_scores
add constraint competency_scores_competency_source_check
check (
  (
    competency_id is not null
    and master_competency_template_id is null
  )
  or
  (
    competency_id is null
    and master_competency_template_id is not null
  )
);


-- One master competency score per attempt.

create unique index if not exists uq_scores_attempt_master_competency
on competency_scores (
  attempt_id,
  master_competency_template_id
)
where master_competency_template_id is not null;



-- ============================================================================
-- PART 2 — ENFORCE THE INTEGRATEU 1–4 PROFICIENCY SCALE
-- ============================================================================

-- Historical scores generated by the old 1–5 algorithm may contain Level 5.
-- Under the approved IntegrateU scale, Level 4 is the maximum.

update competency_scores
set estimated_level = 4
where estimated_level > 4;


alter table competency_scores
drop constraint if exists competency_scores_estimated_level_check;


alter table competency_scores
add constraint competency_scores_estimated_level_check
check (
  estimated_level between 1 and 4
);



