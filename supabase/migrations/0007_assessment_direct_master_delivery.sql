with tech_assessment as (

  select id, name

  from assessments

  where client_id is null
    and name = 'Technician I — Entry Level Pre-Assessment'
    and is_current = true

  order by version desc

  limit 1

),

question_counts as (

  select
    q.assessment_id,
    count(*) as materialized_questions

  from assessment_questions q

  where q.source_master_question_id is not null

  group by q.assessment_id

),

answer_key_counts as (

  select
    q.assessment_id,
    count(*) as secure_answer_keys

  from assessment_questions q

  join assessment_question_answer_keys k
    on k.question_id = q.id

  where q.source_master_question_id is not null

  group by q.assessment_id

),

blueprint_counts as (

  select
    b.assessment_id,
    count(*) as blueprint_rules,
    sum(b.question_count) as blueprint_question_total

  from assessment_blueprint_rules b

  group by b.assessment_id

)

select

  a.name as assessment,

  coalesce(
    q.materialized_questions,
    0
  ) as materialized_questions,

  coalesce(
    k.secure_answer_keys,
    0
  ) as secure_answer_keys,

  coalesce(
    b.blueprint_rules,
    0
  ) as blueprint_rules,

  coalesce(
    b.blueprint_question_total,
    0
  ) as blueprint_question_total

from tech_assessment a

left join question_counts q
  on q.assessment_id = a.id

left join answer_key_counts k
  on k.assessment_id = a.id

left join blueprint_counts b
  on b.assessment_id = a.id;